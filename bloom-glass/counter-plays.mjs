const shortWay=way=>way==='direct'?'直递':'双回折';
export function pairEnding(l,first,pair){
  const data=stories[l.play.coda.baseId][first][pair];
  return data?{title:data[0],story:data[1]}:null;
}
export function pairLabel(l,first,pair){
  const stops=tailPage(l).shortStops;
  return pairOrders(first).map(o=>'经'+stops[Number(o[1])]+'的笺'+shortWay(wayFor(pair,o))).join(' ／ ');
}
export function deliveryLabel(legs){
  return [...legs].map(v=>v==='d'?'直递':'回折').join(' → ');
}
